def faq(section):
    items = []
    for q, a in re.findall(r'<details><summary>(.*?)</summary><p>(.*?)</p></details>', section, flags=re.S):
        items.append({'@type': 'Question', 'name': html.unescape(re.sub('<[^>]+>', '', q)),
                      'acceptedAnswer': {'@type': 'Answer', 'text': html.unescape(re.sub('<[^>]+>', '', a))}})
    return {'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': items}


def ld(obj):
    return '<script type="application/ld+json">' + json.dumps(obj, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/') + '</script>'


def build(lang, key, src, sections, legal, not_found=False):
    idx = 0 if lang == 'tr' else 1
    other = 1 - idx
    s = src
    # --- main content: only this page
    main_start = s.index('<main id="main" tabindex="-1">\n') + len('<main id="main" tabindex="-1">\n')
    main_end = s.index('</main>')
    if not_found:
        section = NOT_FOUND
    elif key in ('gizlilik', 'cerezler'):
        section = legal_section(lang, key, legal)
    else:
        section = sections[key].replace('<section class="page"', '<section class="page active"', 1)
        section = re.sub(r'(<img class="pagehero-img"[^>]*?) loading="lazy"', r'\1 fetchpriority="high"', section, count=1)
    s = s[:main_start] + section + '\n' + s[main_end:]

    # --- head
    if not_found:
        title, desc = 'Sayfa bulunamadı | Focussan', 'Aradığınız sayfa bulunamadı.'
    else:
        title, desc = META[lang][key]
    s = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{html.escape(desc)}">', s, count=1)
    s = re.sub(r'<title>[^<]*</title>', f'<title>{html.escape(title)}</title>', s, count=1)
    if key != 'anasayfa' or not_found:
        s = re.sub(r'<link rel="preload" href="images/hero-poster\.webp"[^>]*>', '', s, count=1)
    head = ['<link rel="icon" href="/favicon.ico" sizes="any"><link rel="icon" type="image/png" href="/icon-192.png"><link rel="apple-touch-icon" href="/apple-touch-icon.png">']
    if not_found:
        head.append('<meta name="robots" content="noindex">')
    else:
        path, alt = PAGES[key][idx], PAGES[key][other]
        tr_p, en_p = PAGES[key][0], PAGES[key][1]
        og_img = url(f'/images/og/{PAGES[key][2]}.jpg')
        head += [f'<link rel="canonical" href="{url(path)}">',
                 f'<link rel="alternate" hreflang="tr" href="{url(tr_p)}"><link rel="alternate" hreflang="en" href="{url(en_p)}"><link rel="alternate" hreflang="x-default" href="{url(tr_p)}">',
                 f'<meta property="og:type" content="website"><meta property="og:site_name" content="Focussan"><meta property="og:locale" content="{"tr_TR" if lang == "tr" else "en_US"}">'
                 f'<meta property="og:title" content="{html.escape(title)}"><meta property="og:description" content="{html.escape(desc)}"><meta property="og:url" content="{url(path)}">'
                 f'<meta property="og:image" content="{og_img}"><meta property="og:image:width" content="1200"><meta property="og:image:height" content="630"><meta name="twitter:card" content="summary_large_image">',
                 ld(business(lang))]
        if key != 'anasayfa':
            head.append(ld(breadcrumb(lang, key)))
        if key == 'sss':
            head.append(ld(faq(section)))
    if key in ('gizlilik', 'cerezler'):
        s = s.replace('</style>', LEGAL_CSS + '\n</style>', 1)
    s = re.sub(r'<link rel="alternate" hreflang="tr" href="[^"]*"><link rel="alternate" hreflang="en" href="[^"]*">', ''.join(head), s, count=1)

    # --- internal links and language switch
    def map_link(m):
        k = m.group(1)
        return f'href="{PAGES[k][idx] if k in PAGES else PAGES["anasayfa"][idx]}"'
    s = re.sub(r'href="#/([a-z-]*)"', map_link, s)
    switch_target = PAGES['anasayfa'][other] if not_found else PAGES[key][other]
    s = re.sub(r'(<a class="lang-switch" href=")[^"]*', r'\g<1>' + switch_target, s, count=1)
    if not not_found:
        s = s.replace(f'<a data-route="{key}" href=', f'<a data-route="{key}" class="active" aria-current="page" href=', 1)

    # --- page-specific WhatsApp message
    text = WA_TEXT[lang].get(key, WA_TEXT[lang]['*'])
    s = s.replace(f'href="{WA}"', f'href="{WA}?text={quote(text)}"')

    # --- scripts: drop the hash router
    s = re.sub(r"const pageTitles=\{.*?\};\n", '', s, count=1)
    s = re.sub(r"function showPage\(\)\{.*?routed=true;\}\n", '', s, count=1)
    for line in ("document.addEventListener('click',event=>{const link=event.target.closest('a[href^=\"#/\"]');if(!link)return;const key=link.getAttribute('href').slice(2).split('/')[0];if(document.getElementById('page-'+key)){event.preventDefault();if(location.hash==='#/'+key)showPage();else location.hash='/'+key;}});\n",
                 "window.addEventListener('hashchange',showPage);\n",
                 "document.querySelector('.lang-switch').addEventListener('click',event=>{event.preventDefault();location.href=event.currentTarget.getAttribute('href')+location.hash;});\n",
                 "window.addEventListener('load',()=>setTimeout(()=>document.querySelectorAll('.pagehero-img').forEach(img=>{img.loading='eager';}),1500),{once:true});\n"):
        assert line in s, line[:60]
        s = s.replace(line, '', 1)
    s = re.sub(r"\(function\(\)\{const items=\[\.\.\.document\.querySelectorAll\('#page-sss details'\)\].*?\}\)\(\);\n", '', s, count=1, flags=re.S)
    s = s.replace("!document.getElementById('page-anasayfa').classList.contains('active')", "!document.getElementById('page-anasayfa')", 1)
    s = s.replace("window.addEventListener('hashchange',start);", '', 1)
    s = s.replace('showPage();', '', 1)
    assert 'showPage' not in s and 'location.hash' not in s
    if key == 'anasayfa' and not not_found:
        # old single-page links such as /#/sss keep working
        mapping = ','.join(f"'{k}':'{v[idx]}'" for k, v in PAGES.items())
        s = s.replace('</script>\n</body>', "(function(){const m={" + mapping + "};const k=location.hash.replace(/^#\\/?/,'');if(m[k])location.replace(m[k]);})();\n</script>\n</body>", 1)

    # --- root-relative asset paths (pages live in sub-folders)
    s = re.sub(r'(?<=["\'(\s,])(images|fonts|media)/', r'/\1/', s)
    s = s.replace('src="logo.svg"', 'src="/logo.svg"')
    return s


