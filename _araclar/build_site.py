def url(path):
    return BASE + path


def out_file(path):
    if path == '/':
        return 'index.html'
    return path.strip('/') + '.html'


def page_sections(src):
    return {m.group(1): m.group(0) for m in re.finditer(r'^<section class="page" id="page-([a-z-]+)">.*$', src, flags=re.M)}


def legal_section(lang, key, legal):
    body = legal[LEGAL_SRC[(lang, key)]]
    body = re.sub(r'\sdata-astro-cid-\w+', '', body)
    parts = re.match(r'\s*<p>(.*?)</p>\s*<h1>(.*?)</h1>\s*<p>(.*?)</p>(.*)', body, flags=re.S)
    eyebrow, h1, updated, rest = parts.groups()
    return (f'<section class="page active" id="page-{key}"><div class="pagehero"><div class="wrap"><div class="eyebrow">{"Hukuki" if lang == "tr" else "Legal"}</div>'
            f'<h1>{h1}</h1><p>{updated}</p></div></div><section class="section"><div class="wrap legal">{rest.strip()}</div></section></section>')


